FILE = "data.json"

# ================= LOAD / SAVE =================
def load():
    if os.path.exists(FILE):
        return json.load(open(FILE, encoding="utf-8"))
    return {"saved": [], "current": None}

def save(data):
    json.dump(
        data,
        open(FILE, "w", encoding="utf-8"),
        ensure_ascii=False,
        indent=2
    )

data = load()

saved = data["saved"]

if data["current"]:
    seats = data["current"]
else:
    seats = [
        [{"name":"", "fixed":False} for _ in row]
        for row in seat_layout
    ]

def persist():
    save({
        "saved": saved,
        "current": seats
    })

# ================= RANDOM ASSIGN =================
def assign():

    empty_positions = []
    fixed_students = []

    for r in range(len(seats)):
        for c in range(len(seats[r])):

            if seats[r][c]["fixed"]:
                fixed_students.append(
                    seats[r][c]["name"]
                )
            else:
                empty_positions.append((r,c))

    free_students = [
        s for s in students
        if s not in fixed_students
    ]

    random.shuffle(free_students)

    for i, (r,c) in enumerate(empty_positions):
        seats[r][c]["name"] = free_students[i]

# ================= ROUTES =================
@app.route("/")
def home():

    return render_template_string(
        HTML,
        seats=seats,
        saved=saved
    )

@app.route("/assign")
def random_assign():

    assign()
    persist()

    return redirect("/")

@app.route("/swap/<int:r1>/<int:c1>/<int:r2>/<int:c2>")
def swap(r1,c1,r2,c2):

    if seats[r1][c1]["fixed"] or seats[r2][c2]["fixed"]:
        return "locked"

    seats[r1][c1]["name"], seats[r2][c2]["name"] = \
    seats[r2][c2]["name"], seats[r1][c1]["name"]

    persist()

    return "ok"

@app.route("/fix/<int:r>/<int:c>")
def fix(r,c):

    seats[r][c]["fixed"] = not seats[r][c]["fixed"]

    persist()

    return "ok"

@app.route("/save")
def save_route():

    # 최대 4개 -> 5번째 저장 시 전체 초기화
    if len(saved) >= 4:
        saved.clear()

    saved.append({
        "time": format_time(),
        "seats": copy.deepcopy([
            [s["name"] for s in row]
            for row in seats
        ])
    })

    persist()

    return redirect("/")

@app.route("/load/<int:i>")
def load_route(i):

    layout = saved[i]["seats"]

    for r in range(len(seats)):
        for c in range(len(seats[r])):

            seats[r][c]["name"] = layout[r][c]

    persist()

    return redirect("/")

@app.route("/delete/<int:i>")
def delete_route(i):

    saved.pop(i)

    persist()

    return redirect("/")

