def now_ict():
    return datetime.utcnow() + timedelta(hours=7)

def format_time():
    dt = now_ict()
    days = ["월","화","수","목","금","토","일"]
    return dt.strftime(f"%Y-%m-%d %H:%M ({days[dt.weekday()]})")

